// E2Eテスト用のサンプルデータ（docs/E2Eテスト.md「4. サンプルデータ」）。
// E2E-01〜04 は、ここで定義した大会・競技情報・選手・スコアを画面操作（UI）で登録・入力する。
// E2E-05・06 は、シナリオの前提データ（補助部分）としてAPIで投入する（tests/e2e/support/seed.ts）。
//
// 選手のスコアは「ラウンドごとの8ホール打数（ホール1〜8順）」で定義する。
// シャッフルの組合せ表はランダムに作られるため、スコアはパーティではなく選手名で引き当てて入力する。

export type PartyAssignmentMethod = 'チーム' | 'シャッフル';
export type TeamRankingMethod = '合計' | '平均';

export type E2ETournament = { name: string; date: string; place: string };

export type E2ECompetition = {
  rounds: number;
  holeInOne: boolean;
  /** ホールインワン時のスコア変換値（変換ありの場合のみ使用） */
  holeInOneValue: number;
  maxPartySize: number;
  method: PartyAssignmentMethod;
  teamBattle: boolean;
  teamMethod?: TeamRankingMethod;
};

export type E2EPlayer = {
  /** 最終的な選手名 */
  name: string;
  /** 最初に登録する選手名（組合せ表作成後に訂正する誤記。未指定は name のまま登録する） */
  typoName?: string;
  /** 生年月日の入力値（西暦 YYYY/MM/DD または 和暦 S/H/R YY.MM.DD） */
  birthInput: string;
  /** 一覧・組合せ表に表示される西暦（YYYY/MM/DD） */
  birthDisplay: string;
  teamName: string;
  /** パーティ固定の場合のパーティ番号 */
  fixedParty?: number;
  /** 不参加 */
  absent?: boolean;
  /** ラウンドごとの8ホール打数（不参加の選手は未定義） */
  rounds?: number[][];
};

export type E2EDataset = {
  tournament: E2ETournament;
  competition: E2ECompetition;
  players: E2EPlayer[];
};

// ---------- スコア作成ヘルパー ----------

/** 8ホール合計が total になる打数（ホールインワンを含まない。16〜113） */
export const T = (total: number): number[] => {
  if (total < 16 || total > 113) throw new Error(`T(${total}) は16〜113で指定してください`);
  return [total - 14, 2, 2, 2, 2, 2, 2, 2];
};

/** 2ラウンドの合計が total になる打数（ホールインワンを含まない。total は32以上） */
const split2 = (total: number): number[][] => [T(Math.floor(total / 2)), T(total - Math.floor(total / 2))];

type Opt = Partial<Pick<E2EPlayer, 'typoName' | 'fixedParty' | 'absent' | 'rounds'>>;

const p = (name: string, birthInput: string, birthDisplay: string, teamName: string, opt: Opt = {}): E2EPlayer => ({
  name,
  birthInput,
  birthDisplay,
  teamName,
  ...opt,
});

